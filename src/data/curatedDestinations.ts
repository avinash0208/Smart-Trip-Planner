const normalize = (value: string) => value.toLowerCase().trim()

export const findCuratedDestination = (name: string, subtitle = ''): CuratedDestination | null => {
  const nameNorm = normalize(name)
  const subtitleNorm = normalize(subtitle)

  return (
    curatedDestinations.find((destination) => {
      const candidates = [destination.city, ...destination.aliases].map(normalize)
      return candidates.some(
        (candidate) => nameNorm.includes(candidate) || candidate.includes(nameNorm) || (subtitleNorm && subtitleNorm.includes(candidate))
      )
    }) || null
  )
}
